import numpy as np

# ------------------------------------------------------------
# 第一部分：热身（不用改，直接运行，观察输出）
# ------------------------------------------------------------
scores_demo = np.array([88, 92, 75, 60, 95])

print("原成绩：   ", scores_demo)
print("每人加5分：", scores_demo + 5)
print("平均分：   ", scores_demo.mean())
print("是否及格： ", scores_demo >= 60)
print("及格人数： ", (scores_demo >= 60).sum())
print()


# ------------------------------------------------------------
# 第二部分：过关任务（在这里作答）
# ------------------------------------------------------------
scores = np.array([88, 92, 75, 60, 95, 45, 78])

# TODO 1：算出平均分，赋值给 mean_score
mean_score = scores.mean()

# TODO 2：算出及格（>= 60）的人数，赋值给 pass_count
pass_count = (scores >= 60).sum()

# TODO 3：算出及格率，赋值给 pass_rate（用 0~1 的小数表示，不要用百分数）
pass_rate = (scores >= 60).mean()


# ------------------------------------------------------------
# 第三部分：自检区（不要改）
# ------------------------------------------------------------
print("===== 自检 =====")
print("平均分   ->", mean_score, "| 期望 76.14285714285714")
print("及格人数 ->", pass_count, "| 期望 6")
print("及格率   ->", pass_rate, "| 期望 0.8571428571428571")
print()
print("提示：如果输出里带 np.float64(...) 或 np.int64(...)，")
print("     那是 NumPy 的显示方式，数值对就算对。")
