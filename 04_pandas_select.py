import pandas as pd

df = pd.read_csv("students.csv")

# ------------------------------------------------------------
# 第一部分：热身（不用改，直接运行，对照输出理解）
# ------------------------------------------------------------

print("=== 1. 取一列：单中括号 + 列名字符串 ===")
print(df["score"])
print()

print("=== 2. 取多列：双中括号，里面装一个列表 ===")
print(df[["name", "score"]])
print()

print("=== 3. 条件筛选：筛出分数 >= 80 的 ===")
print(df[df["score"] >= 80])
print()

print("=== 4. 多个条件：北京 且 分数 >= 80 ===")
print(df[(df["city"] == "北京") & (df["score"] >= 80)])
print()

print("=== 5. value_counts：每个城市有几个人 ===")
print(df["city"].value_counts())
print()

print("=== 6. 缺失值在比较时的表现 ===")
print("score < 60 的结果：")
print(df["score"] < 60)
print()


# ------------------------------------------------------------
# 第二部分：过关任务（在这里作答）
# ------------------------------------------------------------

# TODO 1：筛出所有"上海"的学生，存给 shanghai_df
shanghai_df = df[df["city"] == "上海"]

# TODO 2：筛出"分数低于 60 分"的学生，存给 failed_df
#         注意：两个缺考的（空分数）应该被排除，不算不及格
failed_df = df[df["score"] < 60]

# TODO 3：统计每个城市有多少人，存给 city_counts
city_counts = df["city"].value_counts()


# ------------------------------------------------------------
# 第三部分：自检区（不要改）
# ------------------------------------------------------------
print("===== 自检 =====")
print("上海学生人数 ->", len(shanghai_df), "| 期望 4")
print("不及格人数   ->", len(failed_df), "| 期望 1")
print("城市统计     ->")
print(city_counts)
print("   期望：北京 4、上海 4、广州 2")
